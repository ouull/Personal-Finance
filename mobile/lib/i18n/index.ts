export type TranslationKey = keyof typeof translations.id;

export function useTranslation() {
  const language = useAuthStore((state) => state.user?.language) || 'id';
  
  const t = (key: TranslationKey): string => {
    const langDict = translations[language as keyof typeof translations] || translations.id;
    return langDict[key] || key;
  };

  return { t, language };
}
